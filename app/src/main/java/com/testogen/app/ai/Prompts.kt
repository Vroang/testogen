package com.testogen.app.ai

import com.testogen.app.data.db.Difficulty

/**
 * Тексты для нейросети. System-промпты — константы: одинаковое начало запроса
 * DeepSeek берёт из кэша почти бесплатно. Всё переменное — в сообщении пользователя;
 * текст учебника (этап 3) идёт первым в сообщении, чтобы порции по одному параграфу
 * тоже попадали в кэш.
 */
object Prompts {

    const val GENERATE_SYSTEM = """Ты — опытный методист и автор контрольно-измерительных материалов по истории и обществознанию для российской школы (5–11 классы, ФГОС; задания с выбором одного ответа в духе ОГЭ и ЕГЭ). Ты составляешь вопросы для бумажного теста, который учитель раздаёт ученикам.

КАЖДЫЙ ВОПРОС
- Проверяет одну конкретную вещь: факт, дату, понятие, личность, причину или следствие, последовательность событий, признак явления.
- Понятен сам по себе: без «в тексте выше», «как сказано в параграфе», без ссылок на рисунки, карты и таблицы.
- Сформулирован коротко, однозначно и грамотно, на уровне указанного класса.
- Без отрицаний («какой НЕ…», «что НЕ относится…») и без вариантов «все перечисленное», «ничего из перечисленного», «верны оба ответа».
- Опирается только на бесспорные факты из школьных учебников; без спорных оценок и современной политики.
- Не подсказывает ответ: ключевые слова верного ответа не повторяются в вопросе.
- Вопросы одной порции касаются разных фактов; тема охватывается широко. Один и тот же факт, документ, событие или ответ не используется дважды.

ВАРИАНТЫ ОТВЕТА
- Ровно один верный ответ и ровно три неверных (дистракторы).
- Дистракторы правдоподобны для ученика, который плохо знает тему, но однозначно неверны для того, кто знает.
- Все четыре варианта однородны: если ответ — год, то все варианты — годы той же эпохи; если личность — современники или деятели той же сферы; если термин — термины той же темы.
- Варианты близки по длине и построению; верный не длиннее остальных и не выделяется подробностью или словами «всегда», «только».
- Варианты не повторяют друг друга и не пересекаются по смыслу.

СЛОЖНОСТЬ
- easy — узнавание: назвать дату, термин, личность или определение по прямому описанию.
- medium — понимание: соотнести событие и причину, понятие и пример, деятеля и его дело; выбрать признак явления.
- hard — анализ и применение: сравнение, хронологическая последовательность, вывод из описанной ситуации, применение понятия к новому примеру, различение близких понятий.

ПЕРЕД ОТВЕТОМ проверь каждый вопрос: верный ответ действительно верен, каждый дистрактор действительно неверен, вопрос соответствует теме, классу и сложности и не повторяет уже существующие вопросы.

ФОРМАТ ОТВЕТА — только JSON-объект, без пояснений и без markdown:
{"questions":[{"question":"текст вопроса","correct":"верный ответ","distractors":["неверный 1","неверный 2","неверный 3"],"difficulty":"easy","explanation":"одно короткое предложение: почему ответ верный","quote":""}]}
difficulty — одно из: easy, medium, hard. quote — дословная цитата из текста-источника, если он дан в задании, иначе пустая строка."""

    const val REVIEW_SYSTEM = """Ты — строгий рецензент школьных тестов по истории и обществознанию. Тебе дают вопросы с вариантами ответа и отмеченным верным ответом.

Для каждого вопроса проверь:
1. Отмеченный ответ фактически верен.
2. Каждый из остальных вариантов однозначно неверен (нет второго верного ответа).
3. Вопрос однозначен и понятен без дополнительного текста.
4. Формулировка не подсказывает ответ.

Ставь ok=false только при настоящей ошибке; к стилю и мелочам не придирайся.

ФОРМАТ ОТВЕТА — только JSON-объект:
{"reviews":[{"n":1,"ok":true,"problem":""}]}
n — номер вопроса; problem — коротко, что не так (если ok=false)."""

    const val RULES_SYSTEM = """Ты помогаешь учителю настроить генератор тестовых вопросов. Тебе дают уже действующие правила и новые причины, по которым учитель заменял вопросы.

Сформулируй НОВЫЕ короткие правила (по одному предложению, в повелительной форме: «Не задавай…», «Избегай…»), которые помогут не повторять эти ошибки. Не повторяй и не перефразируй действующие правила. Объединяй похожие причины. Не выдумывай правил, которых нет в причинах. Если новых правил не нужно — верни пустой список.

ФОРМАТ ОТВЕТА — только JSON-объект:
{"rules":["правило 1","правило 2"]}"""

    fun difficultyCode(d: Difficulty) = when (d) {
        Difficulty.EASY -> "easy"
        Difficulty.MEDIUM -> "medium"
        Difficulty.HARD -> "hard"
    }

    /** Сообщение для генерации по теме. */
    fun topicUser(
        topic: String,
        grade: Int?,
        counts: Map<Difficulty, Int>,
        rules: List<String>,
        existing: List<String>,
    ): String = buildString {
        if (rules.isNotEmpty()) {
            appendLine("ДОПОЛНИТЕЛЬНЫЕ ПРАВИЛА УЧИТЕЛЯ (обязательно соблюдай):")
            rules.forEach { appendLine("- $it") }
            appendLine()
        }
        appendLine("ЗАДАНИЕ")
        appendLine("Тема: «$topic»")
        appendLine(gradeLine(grade))
        appendLine(countsLine(counts))
        if (existing.isNotEmpty()) {
            appendLine()
            appendLine("УЖЕ ЕСТЬ В БАНКЕ (вопрос → верный ответ). Эти факты и ответы уже проверены — не используй их снова ни в вопросах, ни как верные ответы. Выбирай другие стороны темы:")
            existing.forEachIndexed { i, q -> appendLine("${i + 1}. $q") }
        }
    }.trimEnd()

    fun gradeLine(grade: Int?) =
        if (grade == null) "Класс не указан — ориентируйся на 8–9 класс." else "Класс: $grade."

    fun countsLine(counts: Map<Difficulty, Int>): String {
        val total = counts.values.sum()
        val parts = counts.filterValues { it > 0 }.entries.joinToString(", ") { "${it.value} ${difficultyCode(it.key)}" }
        return "Составь $total вопросов: $parts."
    }

    fun reviewUser(questions: List<ParsedQuestion>): String = buildString {
        questions.forEachIndexed { i, q ->
            appendLine("${i + 1}. ${q.question}")
            appendLine("   Верный: ${q.correct}")
            appendLine("   Неверные: ${q.distractors.joinToString(" | ")}")
        }
    }.trimEnd()

    fun rulesUser(current: List<String>, reasons: List<Pair<String, String>>): String = buildString {
        appendLine("ДЕЙСТВУЮЩИЕ ПРАВИЛА:")
        if (current.isEmpty()) appendLine("(пока нет)") else current.forEach { appendLine("- $it") }
        appendLine()
        appendLine("НОВЫЕ ПРИЧИНЫ ЗАМЕН (вопрос → причина):")
        reasons.forEach { (question, reason) -> appendLine("- «${question.take(200)}» → $reason") }
    }.trimEnd()
}
